#!/usr/bin/env node
/*
 * Regenerates docs/BRAILLE_MAPPING.md and docs/TECHNICAL_CALCULATIONS.md from the code,
 * so the numbers and tables in the documentation are the ones the app computes.
 * Usage: node tools/generate_docs.js
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const B = require('../js/braille-map.js');
const T = require('../js/braille-timing.js');

const ROOT = path.resolve(__dirname, '..');
const cellsNow = ch => B.getCells(ch);
const catFor = B.categoryOf;
const fmt = ms => (ms / 1000).toFixed(1) + ' s';
const cellText = cells => cells ? cells.map(c => '[' + c.join(',') + ']').join(' then ') : '-';
const esc = s => String(s).replace(/\|/g, '\\|');

// ---------------------------------------------------------------- BRAILLE_MAPPING.md
const rows = B.referenceTable();
const count = st => rows.filter(r => r.status === st).length;
const sourceLine = id => {
  const s = B.SOURCES[id];
  return s ? `[${s.title}](${s.url})` : id;
};
const mappingRows = rows.map(r => {
  const srcs = (r.sources || []).map(id => id).join(', ') || '-';
  return `| \`${esc(r.symbol)}\` | ${r.code} | ${esc(cellText(r.cells))} | ${r.status} | ${srcs} | ${esc(r.note)} |`;
});
const sourceRows = Object.keys(B.SOURCES).map(id => `- \`${id}\`: ${sourceLine(id)}`);

const mappingDoc = `# Braille character mapping

Generated by \`node tools/generate_docs.js\` from \`js/braille-map.js\`. Do not edit by hand.

## Conventions

- **UEB (Unified English Braille).** Used wherever a UEB source defines the symbol. Letters, digits, punctuation, currency and most symbols follow it.
- **BRAILLE-ASCII (computer braille).** Used only for \`#\`, which UEB does not define as a symbol. Its pattern (3-4-5-6) is the UEB numeric indicator, so a standalone \`#\` and a number sign look the same.
- **Case matters.** A capital letter is the UEB capital sign (dot 6) followed by the lower-case letter, so it is two cells. A lesson or quiz teaches the lower-case letter cell.
- **Digits.** UEB writes a digit as a number sign (3-4-5-6) followed by the letters a-j. The number sign is played by the timing engine; the table shows the letter.
- **Multi-cell symbols** are played cell by cell, with a ${T.TIMING.cellGap / 1000} s gap between cells (\`TIMING.cellGap\`).

## Verification status

- \`verified-2-sources\`: two sources agree. Count: ${count('verified-2-sources')}.
- \`verified-1-source\`: one source. Check against the ICEB *Rules of Unified English Braille* before production use. Count: ${count('verified-1-source')}.
- \`unverified-existing\`: kept from the original Grade-1 table and not re-checked in this pass. Count: ${count('unverified-existing')}.
- \`unsupported\`: no verified source defines the character, so the app announces it as unsupported and never draws an invented pattern. Count: ${count('unsupported')}.

Notes on specific entries:

- \`^\`: Braille ASCII uses 4-5 for the caret. This table uses the UEB pattern (4, then 2-6).
- \`"\`: the opening mark is 2-3-6 and the closing mark is 3-5-6. The form depends on position; the table shows the opening form.
- \`?\`: 2-3-6 after a word. Standing alone it is 5-6, 2-3-6.
- \`÷\`: taken from the BANA NLS guide (\`.="/\`), which is decoded as dot 5 then Braille ASCII \`/\` (3-4). liblouis does not define it.
- \`₹\`, \`×\`, \`±\`, \`≠\`: not defined in the consulted sources. Shown as unsupported.
- Hindi (Devanagari) and Marathi Bharati Braille are **not implemented**. No verified table was wired in, and none was invented. The Braille mode for them is reserved and returns no mapping.

## Mapping table

| Symbol | Code | Cells | Status | Sources | Note |
|---|---|---|---|---|---|
${mappingRows.join('\n')}

## Sources

${sourceRows.join('\n')}

Every source above was fetched during the verification pass. Where a source gave dot numbers in a notation (for example the BANA guide's dot-locator form), the decoding is described in the note of the entry. Re-verify before production use.
`;

// ---------------------------------------------------------------- TECHNICAL_CALCULATIONS.md
const samples = [
  ['One lower-case letter (a)', 'a'],
  ['One capital letter (A): capital sign + letter', 'A'],
  ['One digit (5)', '5'],
  ['One space', ' '],
  ['One two-cell symbol (@)', '@'],
  ['12-character UPI ID "merchant@upi"', 'merchant@upi'],
  ['12-character UPI ID "rahul123@ybl" (demo)', 'rahul123@ybl'],
  ['Decoded payment URL from the brief (whole string)', 'upi://pay?pa=merchant@upi&pn=Store&am=500&cu=INR&tn=Payment']
];
const timingRows = samples.map(([label, text]) => {
  const len = [...text].length;
  const t1 = T.estimateMs(text, 1, cellsNow, catFor);
  const t14 = T.estimateMs(text, 1.4, cellsNow, catFor);
  const t2 = T.estimateMs(text, 2, cellsNow, catFor);
  return `| ${label} | ${len} | ${fmt(t1)} | ${fmt(t14)} | ${fmt(t2)} |`;
});

function entropy(ps) { return -ps.reduce((s, p) => (p > 0 ? s + p * Math.log2(p) : s), 0); }
const n = 12;                                  // example VPA length
const alphabet = 36;                           // a-z and 0-9, uniform, i.i.d. (model assumption)
const totalBits = n * Math.log2(alphabet);
const categoryPerChar = entropy([26 / alphabet, 10 / alphabet]);
const categoryBits = n * categoryPerChar;
const leak = (categoryBits / totalBits) * 100;

const techDoc = `# Technical calculations

Generated by \`node tools/generate_docs.js\` from \`js/braille-timing.js\` and \`js/braille-map.js\`.
These are **calculated from the code's timing constants**, not measured on a device. Measured playback on
real hardware has not been done.

## 1. Playback time

Timing constants (ms, at 1x): beforeChar ${T.TIMING.beforeChar}, dotVibration ${T.TIMING.dotVibration},
dotGap ${T.TIMING.dotGap}, afterLastDot ${T.TIMING.afterLastDot}, beforeNextChar ${T.TIMING.beforeNextChar},
spacePulse ${T.TIMING.spacePulse}, cellGap ${T.TIMING.cellGap}.

Per 6-dot cell: 6 slots x ${T.TIMING.dotVibration} ms + 5 gaps x ${T.TIMING.dotGap} ms = ${6 * T.TIMING.dotVibration + 5 * T.TIMING.dotGap} ms.

| Input | Length | 1x | 1.4x | 2x |
|---|---|---|---|---|
${timingRows.join('\n')}

The default readout speaks only the payee ID, so the relevant rows are the UPI ID rows.
The capital row shows the cost of the extra cell.

## 2. Privacy: category-only leakage (theoretical)

This is a **theoretical estimate under an explicit model**, not a measured privacy result.

Model: an ID of ${n} characters, each drawn independently and uniformly from a ${alphabet}-symbol alphabet
(a-z and 0-9). The only information disclosed by category-only audio is the category of each character
(letter or digit).

- Total information in the ID: ${n} x log2(${alphabet}) = ${totalBits.toFixed(2)} bits.
- Category information per character: H(26/36, 10/36) = ${categoryPerChar.toFixed(4)} bits.
- Category information revealed: ${n} x ${categoryPerChar.toFixed(4)} = ${categoryBits.toFixed(2)} bits.
- Estimated leakage: ${categoryBits.toFixed(2)} / ${totalBits.toFixed(2)} = **${leak.toFixed(1)} %**.

Real VPAs are not uniform random strings, so the true figure depends on the population of IDs and is not estimated here.

## 3. What is NOT calculated here

- Measured playback time on real phones (the Vibration API is not available on iOS Safari).
- User performance, accuracy or preference. No user study has been run.
- Speech output duration (depends on the browser's text-to-speech voice).
`;

fs.writeFileSync(path.join(ROOT, 'docs', 'BRAILLE_MAPPING.md'), mappingDoc);
fs.writeFileSync(path.join(ROOT, 'docs', 'TECHNICAL_CALCULATIONS.md'), techDoc);
console.log('wrote docs/BRAILLE_MAPPING.md and docs/TECHNICAL_CALCULATIONS.md');
console.log(JSON.stringify({ rows: rows.length, status: { v2: count('verified-2-sources'), v1: count('verified-1-source'), unverified: count('unverified-existing'), unsupported: count('unsupported') } }));
