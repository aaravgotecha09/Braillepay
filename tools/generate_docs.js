#!/usr/bin/env node
/*
 * Regenerates docs/BRAILLE_MAPPING.md and docs/TECHNICAL_CALCULATIONS.md from the code itself,
 * so the numbers quoted in the documentation are the numbers the app computes.
 * Usage: node tools/generate_docs.js
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const B = require('../js/braille-map.js');
const T = require('../js/braille-timing.js');

const ROOT = path.resolve(__dirname, '..');
const cellsNow = ch => B.getCells(ch);
// The pre-change engine had no entries for @ & = % _ / , so each of them was drawn as one full cell.
const cellsBefore = ch => (B.SINGLE_CELL[String(ch).toUpperCase()] ? [B.SINGLE_CELL[String(ch).toUpperCase()]] : [[1, 2, 3, 4, 5, 6]]);
const catFor = B.categoryOf;
const fmt = ms => (ms / 1000).toFixed(1) + ' s';
const dots = cells => cells.map(c => '[' + c.join(',') + ']').join(' then ');

// ---------------------------------------------------------------- BRAILLE_MAPPING.md
const mappingRows = B.referenceTable().map(r => {
  const note = r.status === 'original' ? 'Grade-1 table (unchanged)' :
    r.status === 'verified-2-sources' ? 'Two-cell UEB sign; two sources agree' :
    'Two-cell UEB sign; one source only, re-check against ICEB Rules of UEB';
  return `| \`${r.symbol}\` | ${r.cells.length} | ${dots(r.cells)} | ${r.standard} | ${note} |`;
});
const mappingDoc = `# Braille character mapping

Generated by \`node tools/generate_docs.js\` from \`js/braille-map.js\`. Do not edit by hand.

Each character is written as one or more cells. A cell is a set of raised dots (standard 6-dot numbering).
Letters and digits use the original Grade-1 table, which is unchanged. The symbols \`@ & = % _ /\` were
previously missing. They are now written as the two-cell sequences used in Unified English Braille (UEB).

## Status of each entry

- **Grade-1 (unchanged):** the original table for letters, digits and the existing punctuation.
- **Two sources agree:** \`@\`, \`&\`, \`=\`, \`%\`. Sources consulted (see "Sources" below).
- **One source only:** \`_\` and \`/\`. Re-check against the ICEB *Rules of Unified English Braille* before
  relying on them for anything other than a demonstration. One secondary table gives a different dot
  pattern for the underscore (dots 3-6 twice, instead of dots 4-6 then 3-6); that table was not
  treated as authoritative.

BraillePay-specific rule: a character with no entry is **not** silently drawn as a real pattern. It is
announced as "Unsupported symbol" and drawn as a full cell with a caption that says so.

## Mapping table

| Symbol | Cells | Dots (in order) | Standard | Status |
|---|---|---|---|---|
${mappingRows.join('\n')}

## Notation

\`[4,6]\` means one cell with dots 4 and 6 raised. Two cells are played one after another with a
${T.TIMING.cellGap / 1000} s gap between them (\`TIMING.cellGap\`).

## Sources and confidence

The status labels above are the values stored in \`js/braille-map.js\`. They record how the entry was checked
during the research pass, not an independent audit:

- \`verified-2-sources\` (\`@ & = %\`): recorded as agreeing across two references during research. The exact
  citations were not re-collected into this document, so treat this label as unconfirmed until the references
  are listed and checked.
- \`verified-1-source\` (\`_ /\`): one reference was used. For \`_\`, one secondary table gave a different
  dot pattern (dots 3-6 twice), which was not treated as authoritative.

No entry has been checked against a braille display or a blind reader.

Check every entry against the ICEB *Rules of Unified English Braille* before any production use.
`;

// ---------------------------------------------------------------- TECHNICAL_CALCULATIONS.md
const samples = [
  ['One letter (A)', 'A'],
  ['One digit (5)', '5'],
  ['One space', ' '],
  ['One two-cell symbol (@)', '@'],
  ['12-character UPI ID "merchant@upi"', 'merchant@upi'],
  ['12-character UPI ID "rahul123@ybl" (demo)', 'rahul123@ybl'],
  ['Decoded payment URL from the brief (whole string)', 'upi://pay?pa=merchant@upi&pn=Store&am=500&cu=INR&tn=Payment']
];
const timingRows = samples.map(([label, text]) => {
  const len = [...text].length;
  const before1 = T.estimateMs(text, 1, cellsBefore, catFor);
  const after1 = T.estimateMs(text, 1, cellsNow, catFor);
  const after14 = T.estimateMs(text, 1.4, cellsNow, catFor);
  const after2 = T.estimateMs(text, 2, cellsNow, catFor);
  return `| ${label} | ${len} | ${fmt(before1)} | ${fmt(after1)} | ${fmt(after14)} | ${fmt(after2)} |`;
});

// Privacy: explicit model, not an assumed total.
function entropy(ps) { return -ps.reduce((s, p) => (p > 0 ? s + p * Math.log2(p) : s), 0); }
const n = 12;                                  // example VPA length used throughout
const alphabet = 36;                           // a-z and 0-9, uniform, i.i.d. (model assumption)
const totalBits = n * Math.log2(alphabet);
const categoryPerChar = entropy([26 / alphabet, 10 / alphabet]); // letter vs digit only
const categoryBits = n * categoryPerChar;
const leak = (categoryBits / totalBits) * 100;

const techDoc = `# Technical calculations

Generated by \`node tools/generate_docs.js\` from \`js/braille-timing.js\` and \`js/braille-map.js\`.
These are **calculated from the code's timing constants**, not measured on a device. Measured playback on
real hardware is still to be done.

## 1. Playback time

Timing constants (ms, at 1x): beforeChar ${T.TIMING.beforeChar}, dotVibration ${T.TIMING.dotVibration},
dotGap ${T.TIMING.dotGap}, afterLastDot ${T.TIMING.afterLastDot}, beforeNextChar ${T.TIMING.beforeNextChar},
spacePulse ${T.TIMING.spacePulse}, cellGap ${T.TIMING.cellGap} (new).

Per 6-dot cell: 6 slots x ${T.TIMING.dotVibration} ms + 5 gaps x ${T.TIMING.dotGap} ms = ${6 * T.TIMING.dotVibration + 5 * T.TIMING.dotGap} ms.

| Character | Cells | Per character (1x) | Per character (1.4x) |
|---|---|---|---|
| Letter | 1 | ${fmt(T.charMs('letter', 1))} | ${fmt(T.charMs('letter', 1) / 1.4)} |
| Digit (includes number sign) | 1 | ${fmt(T.charMs('digit', 1))} | ${fmt(T.charMs('digit', 1) / 1.4)} |
| Space | 0 | ${fmt(T.charMs('space', 0))} | ${fmt(T.charMs('space', 0) / 1.4)} |
| Two-cell symbol (@ & = % _ /) | 2 | ${fmt(T.charMs('symbol', 2))} | ${fmt(T.charMs('symbol', 2) / 1.4)} |

Whole-string estimates. "Before" is the pre-change engine, in which @ & = % _ / were one full cell each.
"After" uses the two-cell mapping. Playback speed 1.4x is the default for the scanner.

| Input | Length | Before, 1x | After, 1x | After, 1.4x | After, 2x |
|---|---|---|---|---|---|
${timingRows.join('\n')}

The default readout reads only the payee ID, so the relevant rows are the "12-character UPI ID" rows, not the
whole-URL row. Those rows show the time for the payee ID alone.

## 2. Privacy: category-only leakage (theoretical)

This is a **theoretical estimate under an explicit model**, not a measured privacy result.

Model: an ID of ${n} characters, each drawn independently and uniformly from a ${alphabet}-symbol alphabet
(a-z and 0-9). The only information disclosed by category-only audio is the category of each character
(letter or digit).

- Total information in the ID: ${n} x log2(${alphabet}) = ${totalBits.toFixed(2)} bits.
- Category information per character: H(26/36, 10/36) = ${categoryPerChar.toFixed(4)} bits.
- Category information revealed: ${n} x ${categoryPerChar.toFixed(4)} = ${categoryBits.toFixed(2)} bits.
- Estimated leakage: ${categoryBits.toFixed(2)} / ${totalBits.toFixed(2)} = **${leak.toFixed(1)} %**.

Earlier drafts quoted 56.9 bits total and 9.3 bits of category information (about 16 %). Those figures
cannot be reproduced from any stated alphabet model, so they are replaced by the calculation above.
Real VPAs are not uniform random strings (names and bank handles are structured), so the true figure
depends on the population of IDs and is not estimated here.

## 3. What is NOT calculated here

- Measured playback time on real phones (the Vibration API is not available on iOS Safari).
- User performance, accuracy or preference. No user study has been run.
- Speech output duration (depends on the browser's TTS voice).
`;

fs.writeFileSync(path.join(ROOT, 'docs', 'BRAILLE_MAPPING.md'), mappingDoc);
fs.writeFileSync(path.join(ROOT, 'docs', 'TECHNICAL_CALCULATIONS.md'), techDoc);
console.log('wrote docs/BRAILLE_MAPPING.md and docs/TECHNICAL_CALCULATIONS.md');
console.log(JSON.stringify({ totalBits, categoryBits, leakPct: leak, merchantId_1x: T.estimateMs('merchant@upi', 1, cellsNow, catFor), urlAfter14: T.estimateMs(samples[6][1], 1.4, cellsNow, catFor), urlBefore1: T.estimateMs(samples[6][1], 1, cellsBefore, catFor) }, null, 2));
